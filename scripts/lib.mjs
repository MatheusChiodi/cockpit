// Shared by the build scripts: where things live and how one mod's files are written.
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

export const root = join(dirname(fileURLToPath(import.meta.url)), '..')

export const json = value => `${JSON.stringify(value, null, 2)}\n`

export const loadCatalog = () => JSON.parse(readFileSync(join(root, 'mods.json'), 'utf8'))

const entriesIn = folder => {
  const dir = join(root, folder)

  return existsSync(dir)
    ? readdirSync(dir)
        .filter(name => name.endsWith('.json'))
        .sort()
        .flatMap(name => JSON.parse(readFileSync(join(dir, name), 'utf8')))
    : []
}

// Catalog entries being written (catalog-parts/) and the ones waiting to land (catalog-pending/).
export const loadParts = () => [...entriesIn('catalog-parts'), ...entriesIn('catalog-pending')]

// A text in the wanted language; English first, then whatever exists.
export const text = (value, lang = 'en') =>
  typeof value === 'string' ? value : (value?.[lang] ?? value?.en ?? value?.pt ?? Object.values(value ?? {})[0] ?? '')

export const moduleOf = name =>
  ['register.tsx', 'register.ts'].find(file => existsSync(join(root, 'mods', name, 'hooks', file)))

const kit = () =>
  `// Generated by the build from kit/kit.tsx. Do not edit by hand.\n${readFileSync(join(root, 'kit', 'kit.tsx'), 'utf8')}`

// Writes plugin.json, hooks.json and, for a mod that draws with the kit, its own copy of it.
export const writeManifest = (catalog, mod) => {
  const dir = join(root, 'mods', mod.name)
  const module = moduleOf(mod.name)

  if (module === undefined) {
    throw new Error(`${mod.name}: hooks/register.ts(x) is missing`)
  }

  // Every plugin stands alone, so the kit travels as a copy.
  if (readFileSync(join(dir, 'hooks', module), 'utf8').includes("from './kit'")) {
    writeFileSync(join(dir, 'hooks', 'kit.tsx'), kit())
  }

  const manifest = {
    name: mod.name,
    version: catalog.version,
    description: text(mod.description),
    author: catalog.owner,
    keywords: ['claude-code', 'mod', mod.category],
  }

  if (existsSync(join(dir, 'types', 'index.d.ts'))) {
    manifest.types = './types/index.d.ts'
  }

  // A panel is switched from the hub, so the hub comes along.
  if (mod.category === 'panel' && mod.hub !== true) {
    manifest.dependencies = ['cockpit']
  }

  mkdirSync(join(dir, '.claude-plugin'), { recursive: true })
  writeFileSync(join(dir, '.claude-plugin', 'plugin.json'), json(manifest))
  writeFileSync(join(dir, 'hooks', 'hooks.json'), json({ modules: [`./${module}`] }))
}
