// Generates each mod's plugin.json + hooks.json, the hub's panel list and marketplace.json from mods.json.
// Usage: node scripts/build-manifests.mjs
import { mkdirSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

import { json, loadCatalog, root, text, writeManifest } from './lib.mjs'

const catalog = loadCatalog()
const groupOrder = Object.keys(catalog.groups)

const panels = catalog.mods
  .filter(mod => mod.category === 'panel' && mod.hub !== true)
  .map(({ name, description, group = 'session' }) => ({
    name,
    group,
    description: Object.fromEntries(catalog.languages.map(lang => [lang, text(description, lang)])),
  }))
  .sort((a, b) => groupOrder.indexOf(a.group) - groupOrder.indexOf(b.group))

// The list the settings pane draws: generated, so it never drifts from the catalog.
writeFileSync(
  join(root, 'mods', 'cockpit', 'hooks', 'panels.ts'),
  `// Generated by scripts/build-manifests.mjs from mods.json. Do not edit by hand.
export type Lang = ${catalog.languages.map(lang => `'${lang}'`).join(' | ')}

export type Panel = { name: string; group: string; description: Record<Lang, string> }

export const GROUPS: Record<string, Record<Lang, string>> = ${JSON.stringify(catalog.groups, null, 2)}

export const PANELS: readonly Panel[] = ${JSON.stringify(panels, null, 2)}
`,
)

const plugins = catalog.mods.map(mod => {
  writeManifest(catalog, mod)

  return {
    name: mod.name,
    source: `./mods/${mod.name}`,
    description: text(mod.description),
    category: mod.category,
  }
})

mkdirSync(join(root, '.claude-plugin'), { recursive: true })
writeFileSync(
  join(root, '.claude-plugin', 'marketplace.json'),
  json({
    name: catalog.marketplace,
    description: text(catalog.description),
    owner: catalog.owner,
    plugins,
  }),
)

console.log(`${plugins.length} mods in ${catalog.marketplace}`)
