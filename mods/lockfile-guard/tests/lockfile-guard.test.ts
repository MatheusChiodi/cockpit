import { expect, test } from 'claude-code/testing'

const edit = (file_path: string, id: string) => ({
  tool: 'Edit' as const,
  file_path,
  old_string: 'a',
  new_string: 'b',
  tool_use_id: id,
})

test('refuses editing lockfiles and lets package.json through', async ($, on) => {
  on('tool.call', { tool: 'Edit' }, () => ({ result: undefined as never }))

  for (const file_path of ['package-lock.json', 'web/yarn.lock', 'C:\\app\\pnpm-lock.yaml', 'Cargo.lock']) {
    const answer = await $.tool.call(edit(file_path, `e-${file_path}`))
    expect(answer.deny, file_path).toContain('is generated by the package manager')
  }

  const manifest = await $.tool.call(edit('package.json', 'e-ok'))
  expect(manifest.deny).toBeUndefined()
})

test('speaks the language set in the hub', async ($, on) => {
  on('tool.call', { tool: 'Edit' }, () => ({ result: undefined as never }))
  // Stands in for the hub: answers the language it would hold.
  on('state.get', { plugin: 'cockpit', key: 'lang' }, () => ({ value: { value: 'pt', version: 1 } }))

  const answer = await $.tool.call(edit('package-lock.json', 'pt-1'))
  expect(answer.deny).toContain('lockfile-guard: package-lock.json é gerado pelo gerenciador de pacotes')
})
