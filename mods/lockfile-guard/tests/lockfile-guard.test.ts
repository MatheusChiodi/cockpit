import { expect, test } from 'claude-code/testing'

const edit = (file_path: string, id: string) => ({
  tool: 'Edit' as const,
  file_path,
  old_string: 'a',
  new_string: 'b',
  tool_use_id: id,
})

test('refuses editing lockfiles and lets package.json through', async ($, on) => {
  on('tool.call', { tool: 'Edit' }, () => ({ result: undefined as never }))

  for (const file_path of ['package-lock.json', 'web/yarn.lock', 'C:\\app\\pnpm-lock.yaml', 'Cargo.lock']) {
    const answer = await $.tool.call(edit(file_path, `e-${file_path}`))
    expect(answer.deny, file_path).toContain('is generated by the package manager')
  }

  const manifest = await $.tool.call(edit('package.json', 'e-ok'))
  expect(manifest.deny).toBeUndefined()
})

test('speaks the language set in the hub', async ($, on) => {
  on('tool.call', { tool: 'Edit' }, () => ({ result: undefined as never }))
  // Stands in for the hub: answers the language it would hold.
  on('state.get', { plugin: 'cockpit', key: 'lang' }, () => ({ value: { value: 'pt', version: 1 } }))

  const answer = await $.tool.call(edit('package-lock.json', 'pt-1'))
  expect(answer.deny).toContain('lockfile-guard: package-lock.json é gerado pelo gerenciador de pacotes')
})

test('knows the lockfiles of every package manager, in any letter case', async ($, on) => {
  on('tool.call', { tool: 'Edit' }, () => ({ result: undefined as never }))

  for (const file_path of [
    'npm-shrinkwrap.json',
    'bun.lockb',
    'bun.lock',
    'api/poetry.lock',
    'uv.lock',
    'Pipfile.lock',
    'composer.lock',
    'Gemfile.lock',
    'go.sum',
    'YARN.LOCK',
  ]) {
    expect((await $.tool.call(edit(file_path, `k-${file_path}`))).deny, file_path).toContain('lockfile-guard:')
  }
})

test('lets lookalike names and manifests through', async ($, on) => {
  on('tool.call', { tool: 'Edit' }, () => ({ result: undefined as never }))

  for (const file_path of ['my-package-lock.json', 'yarn.lock.bak', 'go.mod', 'Cargo.toml', 'docs/yarn.lock.md', 'Gemfile']) {
    expect((await $.tool.call(edit(file_path, `l-${file_path}`))).deny, file_path).toBeUndefined()
  }
})

test('refuses a Write too, before it reaches the tool', async ($, on) => {
  let ran = 0
  on('tool.call', { tool: 'Write' }, () => {
    ran += 1

    return { result: undefined as never }
  })

  const answer = await $.tool.call({ tool: 'Write', file_path: '/repo/pnpm-lock.yaml', content: 'x', tool_use_id: 'w-1' })
  expect(answer.deny).toBe(
    'lockfile-guard: /repo/pnpm-lock.yaml is generated by the package manager. Run the install/update command instead of editing it by hand.',
  )
  expect(ran).toBe(0)
})

test('speaks Spanish when the hub says so', async ($, on) => {
  on('tool.call', { tool: 'Edit' }, () => ({ result: undefined as never }))
  on('state.get', { plugin: 'cockpit', key: 'lang' }, () => ({ value: { value: 'es', version: 1 } }))

  const answer = await $.tool.call(edit('Cargo.lock', 'es-1'))
  expect(answer.deny).toBe(
    'lockfile-guard: Cargo.lock lo genera el gestor de paquetes. Ejecuta el comando de install/update en lugar de editarlo a mano.',
  )
})
